function pickNewQuestions(pool, n){
  return shuffle(pool).slice(0, Math.min(n, pool.length));
}
/* Взвешенный повтор виденных: чем реже встречался — тем выше шанс */
function pickSeenWeighted(pool, n){
  const seen = S.seen || {};
  const bag = pool.map(function(q){
    const cnt = seen[q.id] || 0;
    return { q:q, w: (1 / (1 + cnt * 0.35)) * (0.6 + Math.random() * 0.8) };
  });
  const out = [];
  while(out.length < n && bag.length){
    let total = 0;
    for(let i = 0; i < bag.length; i++) total += bag[i].w;
    let r = Math.random() * total, idx = 0;
    for(let i = 0; i < bag.length; i++){ r -= bag[i].w; if(r <= 0){ idx = i; break; } }
    out.push(bag[idx].q);
    bag.splice(idx, 1);
  }
  return out;
}
function pickHybrid(pool, n){
  if(!pool || !pool.length) return [];
  const fresh = pickNewQuestions(pool, n);
  if(fresh.length >= n) return fresh;
  const rest = pool.filter(function(q){ return fresh.indexOf(q) === -1; });
  return fresh.concat(pickSeenWeighted(rest, n - fresh.length));
}

/* Перемешивание вариантов: верный находится по тексту */
function buildOptionOrder(q){
  const n = q.options.length;
  const correctText = q.options[q.correct];
  const prev = (S.lastPos && typeof S.lastPos[q.id] === 'number') ? S.lastPos[q.id] : -1;
  const base = [];
  for(let i = 0; i < n; i++) base.push(i);

  let order = shuffle(base), slot = -1;
  for(let t = 0; t < 5; t++){
    order = shuffle(base);
    const texts = order.map(function(orig){ return q.options[orig]; });
    slot = texts.indexOf(correctText);
    if(prev < 0 || slot !== prev) break;
  }
  return { order: order, slot: slot };
}

