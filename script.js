function renderErrors(res){
  const list = document.getElementById('errList');
  if(!list) return;
  list.innerHTML = '';
  if(!res || !res.errors || !res.errors.length){
    list.innerHTML = '<div class="hist-empty">Ошибок нет — отлично!</div>';
    return;
  }
  res.errors.forEach(function(e){
    const q = e.q;
    const card = document.createElement('div');
    card.className = 'err-card';
    const yours = (e.picked >= 0 && q.options[e.picked])
      ? '<div class="pill no"><b>Ваш ответ:</b> ' + esc(q.options[e.picked]) + '</div>'
      : '<div class="pill no"><b>Ваш ответ:</b> время вышло</div>';
    card.innerHTML =
      '<div class="err-q">' + esc(q.text) + '</div>' +
      '<div class="pill ok"><b>Верный ответ:</b> ' + esc(q.options[q.correct] || '—') + '</div>' +
      yours;
    list.appendChild(card);
  });
}

