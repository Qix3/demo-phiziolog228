function parseBank(raw){
  const txt = String(raw || '')
    .split(/\r?\n/)
    .filter(function(l){ return !l.trim().startsWith('//'); })
    .join('\n')
    .trim();
  if(!txt) throw new Error('Банк пуст');
  const qs = (txt[0] === '[' || txt[0] === '{') ? parseBankJSON(txt) : parseBankText(txt);
  if(!qs || !qs.length) throw new Error('В банке нет валидных вопросов');
  return qs;
}

function parseBankJSON(txt){
  let data;
  try{
    data = JSON.parse(txt);
  }catch(err){
    const s = txt.indexOf('['), e = txt.lastIndexOf(']');
    if(s >= 0 && e > s) data = JSON.parse(txt.slice(s, e + 1));
    else throw new Error('Не удалось разобрать JSON банка: ' + err.message);
  }
  if(!Array.isArray(data)) data = data.questions || [];

  const out = [];
  const seenIds = new Set();

  data.forEach(function(item, i){
    if(!item || typeof item !== 'object') return;

    const text = String(item.q || item.text || '').trim();
    let options = Array.isArray(item.a) ? item.a
                : Array.isArray(item.answers) ? item.answers
                : [];
    options = options.map(function(x){ return String(x).trim(); }).filter(Boolean);

    let corr = -1;
    if(typeof item.c === 'number') corr = item.c;
    else if(typeof item.correct === 'number') corr = item.correct;
    else if(typeof item.ci === 'number') corr = item.ci;
    else if(typeof item.correct === 'string') corr = options.indexOf(item.correct.trim());

    if(!text || options.length < 2 || corr < 0 || corr >= options.length) return;
    if(options.length > 4) options = options.slice(0, 4);

    const id = (item.id != null && item.id !== '') ? String(item.id) : 'q' + i;
    if(seenIds.has(id)) return;
    seenIds.add(id);

    const topic = String(item.topic || item.t || 'Общее').trim() || 'Общее';
    out.push({ id:id, text:text, options:options, correct:corr, topic:topic });
  });

  if(!out.length) throw new Error('В банке нет валидных вопросов');
  return out;
}

function parseBankText(txt){
  const lines = txt.split(/\r?\n/);
  const out = [];
  let cur = null;
  lines.forEach(function(lineRaw){
    const line = lineRaw.replace(/\u00a0/g, ' ').trim();
    if(!line) return;
    const m = line.match(/^(\d+)[.)]\s*(.*)$/);
    if(m){
      if(cur) out.push(cur);
      cur = { id:'q' + out.length, text:m[2].replace(/\s+/g, ' ').trim(), options:[], correct:-1, topic:'Общее' };
      return;
    }
    if(!cur) return;
    const isCorr = /^#.*#$/.test(line);
    const text = line.replace(/^#\s*/, '').replace(/\s*#$/, '').trim();
    if(!text) return;
    if(cur.correct === -1 && isCorr) cur.correct = cur.options.length;
    cur.options.push(text);
  });
  if(cur) out.push(cur);

  return out.filter(function(q){
    return q.text && q.options.length >= 2 && q.correct >= 0 && q.correct < q.options.length;
  });
}

