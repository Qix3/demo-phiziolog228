/* ==========================================================
   Эффекты: кольцо-пульс таймера, «кровоток» прогресса,
   ЭКГ-волна на 100 %. Только transform / opacity.
   ========================================================== */
const FX = (function(){
  let raf = 0;
  let lastTs = 0;
  let timer = null;
  let finaleT = 0;

  const RING_C = 2 * Math.PI * 21;
  const PULSE_SPEED = { calm:1.0, mid:1.15, warn:1.75, alarm:2.4 };

  let pulseState = 'mid';

  function ensureLoop(){
    if(raf || document.hidden) return;
    lastTs = 0;
    raf = requestAnimationFrame(frame);
  }

  function frame(ts){
    raf = 0;
    let dt = lastTs ? (ts - lastTs) : 16;
    lastTs = ts;
    if(dt > 100) dt = 100;
    if(timer) paintTimer(dt);
    if(timer) raf = requestAnimationFrame(frame);
    else lastTs = 0;
  }

  /* Два коротких удара за период — «лаб-даб» */
  function heartbeat(ph){
    const p = (ph % 0.86) / 0.86;
    const a = Math.exp(-Math.pow((p - 0.08) / 0.045, 2));
    const b = Math.exp(-Math.pow((p - 0.22) / 0.060, 2)) * 0.62;
    return Math.max(a, b);
  }

  function paintRing(frac){
    const arc = document.getElementById('timerArc');
    if(!arc) return;
    arc.style.strokeDashoffset = (RING_C * (1 - clamp(frac, 0, 1))).toFixed(2);
  }

  function paintDigits(sec){
    const el = document.getElementById('timerNum');
    if(!el) return;
    el.textContent = fmtDur(sec);
    el.classList.toggle('low', sec > 0 && sec <= 5);
  }

  function startTimer(seconds, sessionOrCb){
    stopTimer();
    const svg = document.querySelector('.tring');
    const total = seconds * 1000;
    timer = {
      deadline: Date.now() + total,
      total: total,
      cb: sessionOrCb,
      active: true,
      phase: Math.random() * 0.86,
      speed: PULSE_SPEED[pulseState] || 1.15,
      pulse: pulseState,
      kick: 0, kickT: 0,
      amp: 0.03, ampTarget: 0.03,
      shownSec: -1,
      hiddenAt: 0,
      svg: svg
    };
    paintRing(1);
    paintDigits(seconds);
    if(svg) svg.style.transform = 'scale(1)';
    ensureLoop();
  }

  function stopTimer(){
    if(timer){ timer.active = false; timer.kick = 0; }
  }

  function killTimer(){
    timer = null;
    const svg = document.querySelector('.tring');
    if(svg) svg.style.transform = 'scale(1)';
  }

  function paintTimer(dt){
    if(document.hidden) return;
    const t = timer;
    if(!t) return;

    if(t.active){
      let remain = t.deadline - Date.now();
      if(remain <= 0){
        remain = 0;
        paintRing(0);
        paintDigits(0);
        t.active = false;
        const cb = t.cb;
        if(cb && typeof cb.timeout === 'function') cb.timeout();
        else if(typeof cb === 'function') cb();
        return;
      }
      const sec = Math.ceil(remain / 1000);
      if(sec !== t.shownSec){
        paintDigits(sec);
        t.shownSec = sec;
      }
      paintRing(remain / t.total);
      t.ampTarget = sec <= 5 ? 0.085 : 0.032;
    }

    if(t.kickT > 0){
      t.kickT -= dt;
      if(t.kickT <= 0){ t.kickT = 0; t.kick = 0; }
      else t.kick *= 0.96;
    }

    const base = PULSE_SPEED[t.pulse] || 1.15;
    t.speed = t.speed + ((base + t.kick) - t.speed) * Math.min(1, dt / 220);
    t.phase += dt / 1000 * t.speed;
    t.amp = t.amp + (t.ampTarget - t.amp) * Math.min(1, dt / 260);

    if(!t.svg) return;
    if(reduceMotion()){
      t.svg.style.transform = 'scale(1)';
      return;
    }
    const b = heartbeat(t.phase);
    t.svg.style.transform = 'scale(' + (1 + t.amp * b).toFixed(4) + ')';
  }

  /* Реакция на ответ: усилить пульс на время */
  function pulseKick(bad){
    if(!timer) return;
    timer.kick = bad ? 1.7 : 0.5;
    timer.kickT = bad ? 850 : 400;
  }

  function setPulse(state){
    const box = document.getElementById('timerBox');
    const effective = reactiveOn() ? state : 'flat';
    pulseState = effective === 'flat' ? 'mid' : effective;
    if(!box) return;
    box.className = 'timer' + (effective === 'mid' ? '' : ' ' + effective);
    if(timer && timer.active) timer.pulse = pulseState;
  }

  function reactiveOn(){
    try{ return (typeof S !== 'undefined') ? !!S.reactive : true; }
    catch(e){ return true; }
  }

  /* Импульс по заполненной части прогресса */
  function flow(widthPx, trackW){
    const el = document.getElementById('pflow');
    if(!el || reduceMotion()) return;
    const room = Math.max(0, Math.round(trackW - widthPx));
    el.style.clipPath = 'inset(0 ' + room + 'px 0 0)';
    if(!el.animate) return;
    el.animate([
      { transform:'translate3d(0,0,0)', opacity:0 },
      { opacity:.92, offset:.16 },
      { opacity:.8, offset:.6 },
      { transform:'translate3d(' + Math.max(0, widthPx - 16) + 'px,0,0)', opacity:0 }
    ], { duration: 560, easing:'cubic-bezier(.25,.7,.3,1)' });
  }

  /* 100 %: волна ЭКГ на весь экран, затем ровная линия под числом */
  function finale(){
    const arena = document.getElementById('ecgArena');
    if(!arena) return;
    arena.classList.remove('run');
    void arena.offsetWidth;
    arena.classList.add('run');
    clearTimeout(finaleT);
    finaleT = setTimeout(function(){ arena.classList.remove('run'); }, 2400);
  }

  function stopFinale(){
    const arena = document.getElementById('ecgArena');
    if(arena) arena.classList.remove('run');
    clearTimeout(finaleT);
  }

  document.addEventListener('visibilitychange', function(){
    if(document.hidden){
      if(timer) timer.hiddenAt = Date.now();
      lastTs = 0;
    }else{
      if(timer && timer.active && timer.hiddenAt){
        timer.deadline += Date.now() - timer.hiddenAt;
      }
      if(timer) timer.hiddenAt = 0;
      ensureLoop();
    }
  });

  return {
    startTimer: startTimer,
    stopTimer: stopTimer,
    killTimer: killTimer,
    setPulse: setPulse,
    pulseKick: pulseKick,
    flow: flow,
    finale: finale,
    startMenu: function(){},
    stopMenu: function(){},
    startSS: function(){},
    stopSS: function(){},
    stopAll: function(){
      stopTimer();
      killTimer();
      stopFinale();
      if(raf){ cancelAnimationFrame(raf); raf = 0; }
    }
  };
})();

